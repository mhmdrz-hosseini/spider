def update_territory_map(shards):
    territory_path = CONTEXT_DIR / "02-content-territory-map.md"

    shards_md_lines = [
        "\n\n---",
        "## 4. Robert Tolone Technical Topic Shards Matrix (Granular 45s Edutainment)",
        f"> **Grounding:** 20 forensic transcripts deconstructed into {len(shards)} atomic, 45-second Instagram Reels shards.",
        "> **Formula:** 0-3s Visceral Hook -> 0-22s Parable/Failure -> 22-28s Iranian Maker Pivot -> 28-40s Mechanical Rule -> 40-45s CTA.\n"
    ]

    for s in shards:
        shards_md_lines.extend([
            f"### [{s['shard_id']}] {s['topic']} — ({s['ring'].upper()})",
            f"- **Source Reference:** `{s['video_id']}` ({s['video_title']})",
            f"- **Target Pillar:** {s['pillar']}",
            f"- **Format:** 45-second Engineered Motion Comic (`motion_comic_v2`)",
            f"- **Hook (0-3s):** *\"{s['hook']}\"*",
            f"- **Act 1 Parable (0-22s):** {s['act_1_parable']}",
            f"- **The Pivot (22-28s):** {s['pivot']}",
            f"- **Act 2 Mechanism (28-40s):** {s['act_2_mechanism']}",
            f"- **Resolution / CTA (40-45s):** {s['cta']}",
            f"- **Practical Takeaway:** `{s['practical_rule']}`\n"
        ])

    content_to_append = "\n".join(shards_md_lines)

    with open(territory_path, "r", encoding="utf-8") as f:
        existing = f.read()

    if "## 4. Robert Tolone Technical Topic Shards Matrix" in existing:
        prefix = existing.split("## 4. Robert Tolone Technical Topic Shards Matrix")[0].rstrip()
        new_content = prefix + content_to_append
    else:
        new_content = existing + content_to_append

    with open(territory_path, "w", encoding="utf-8") as f:
        f.write(new_content)

    print(f"[✓] Successfully updated {territory_path} with {len(shards)} topic shards.")


